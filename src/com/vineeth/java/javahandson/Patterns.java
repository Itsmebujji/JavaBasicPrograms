package com.vineeth.java.javahandson;

public class Patterns {
    public static void main(String[] args) {
        System.out.println("----------------------------------");
        for(int i=5; i>0;i--){
            for(int j=i; j>0;j--){
                System.out.print("*");
            }
            System.out.println("");
        }
        System.out.println("----------------------------------");
        for(int i=5; i>0;i--){
            for(int j=i; j>0;j--){
                System.out.print("*");
            }
            System.out.println("");
        }
    }
}
